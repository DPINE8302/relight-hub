let language = "th";
const copies = new Map(),
  originals = new Map();
export const missing = new Set();
const clean = (s) => s.replace(/\s+/g, " ").trim();
export function thai(text) {
  const key = clean(text);
  if (TH[key]) return TH[key];
  const m = key.match(/^(\d+) m$/);
  if (m) return `${m[1]} ม.`;
  if (!key || /^[\d\s/·↗↑]+$/.test(key) || /^(PUFF|WORLD|INSIDE)$/.test(key))
    return text;
  missing.add(key);
  return text;
}
export const t = (text) => (language === "th" ? thai(text) : text);
export function copy(el, source) {
  if (typeof el === "string") el = document.getElementById(el);
  if (!el) return;
  const prev = copies.get(el);
  if (prev?.source === source && prev.language === language) return;
  copies.set(el, { source, language });
  el.dataset.localized = "true";
  el.textContent = t(source);
}
export function setLanguage(value) {
  language = value;
  document.documentElement.lang = value;
  for (const [node, source] of originals)
    if (node.isConnected) node.textContent = t(source);
  for (const [el, data] of copies) {
    data.language = value;
    el.textContent = t(data.source);
  }
  const button = document.getElementById("languageButton");
  button.textContent = value === "th" ? "EN" : "ไทย";
  button.setAttribute(
    "aria-label",
    value === "th" ? "Switch to English" : "เปลี่ยนเป็นภาษาไทย",
  );
  dispatchEvent(new CustomEvent("languagechange"));
}
export function initLanguage() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest("script,style")) continue;
    const source = clean(node.textContent);
    if (TH[source]) originals.set(node, source);
  }
  document.getElementById("languageButton").onclick = () =>
    setLanguage(language === "th" ? "en" : "th");
  window.__language = {
    set: setLanguage,
    get: () => language,
    missing: () => [...missing],
  };
  setLanguage("th");
}
